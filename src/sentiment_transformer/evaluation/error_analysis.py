"""Reproducible error analysis and linguistic heuristic flagging for Portuguese reviews."""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from sentiment_transformer.constants import (
    COL_COMBINED_TEXT,
    COL_OVERALL_RATING,
    COL_REVIEW_ID,
    COL_REVIEW_TEXT,
    COL_REVIEW_TITLE,
    ERROR_FALSE_NEGATIVE,
    ERROR_FALSE_POSITIVE,
    PORTUGUESE_NEGATION_TERMS,
)

logger = logging.getLogger(__name__)


def detect_portuguese_negation(text: str) -> bool:
    """Heuristic check for common Portuguese negation terms in text.

    Note: This heuristic checks whole-word token matches and does not constitute
    a full syntactic or dependency parse of Portuguese discourse.

    Args:
        text: String of review text.

    Returns:
        True if text contains one or more negation markers, False otherwise.
    """
    if not isinstance(text, str) or not text.strip():
        return False

    clean_text = text.lower()
    for term in PORTUGUESE_NEGATION_TERMS:
        # Match whole word boundary
        pattern = rf"\b{re.escape(term)}\b"
        if re.search(pattern, clean_text):
            return True

    return False


def build_error_analysis(
    predictions_df: pd.DataFrame,
    output_csv_path: str | Path | None = None,
    min_samples_per_category: int = 10,
) -> tuple[pd.DataFrame, dict[str, Any]]:
    """Build reproducible error analysis dataset covering false positives, false negatives, and boundary cases.

    Args:
        predictions_df: DataFrame generated by predictions module.
        output_csv_path: Optional path to save error_analysis.csv.
        min_samples_per_category: Minimum sample count for each error type (default 10).

    Returns:
        Tuple of (error_analysis_df, summary_stats_dict).
    """
    logger.info(
        "Building error analysis from %d prediction records...", len(predictions_df)
    )

    work_df = predictions_df.copy()

    # Determine error type
    # true=0 & pred=1 -> False Positive (predicted positive when actually negative)
    # true=1 & pred=0 -> False Negative (predicted negative when actually positive)
    # true==pred -> Correct
    def classify_error(row: pd.Series) -> str:
        t = int(row["true_label"])
        p = int(row["predicted_label"])
        if t == 0 and p == 1:
            return ERROR_FALSE_POSITIVE
        elif t == 1 and p == 0:
            return ERROR_FALSE_NEGATIVE
        return "correct"

    work_df["error_type"] = work_df.apply(classify_error, axis=1)
    work_df["text_length"] = work_df[COL_COMBINED_TEXT].astype(str).str.len()
    work_df["contains_negation"] = work_df[COL_COMBINED_TEXT].apply(
        detect_portuguese_negation
    )

    # Compute prediction margin / distance from decision boundary (0.5)
    # confidence in predicted class
    work_df["confidence"] = np.where(
        work_df["predicted_label"] == 1,
        work_df["positive_probability"],
        work_df["negative_probability"],
    )
    work_df["distance_from_boundary"] = np.abs(work_df["positive_probability"] - 0.5)

    # Subsets
    fps = work_df[work_df["error_type"] == ERROR_FALSE_POSITIVE]
    fns = work_df[work_df["error_type"] == ERROR_FALSE_NEGATIVE]
    corrects = work_df[work_df["error_type"] == "correct"]

    # Select representative samples:
    # 1. High confidence False Positives (sorted by descending positive probability)
    selected_fps_high_conf = fps.sort_values(
        by="positive_probability", ascending=False
    ).head(min_samples_per_category)
    # 2. High confidence False Negatives (sorted by descending negative probability)
    selected_fns_high_conf = fns.sort_values(
        by="negative_probability", ascending=False
    ).head(min_samples_per_category)
    # 3. Boundary errors (closest to 0.5)
    all_errors = work_df[work_df["error_type"] != "correct"]
    selected_boundary_errors = all_errors.sort_values(
        by="distance_from_boundary", ascending=True
    ).head(min_samples_per_category)
    # 4. High confidence correct predictions
    selected_correct_high_conf = corrects.sort_values(
        by="confidence", ascending=False
    ).head(min_samples_per_category)

    combined_selection = pd.concat(
        [
            selected_fps_high_conf,
            selected_fns_high_conf,
            selected_boundary_errors,
            selected_correct_high_conf,
        ]
    ).drop_duplicates(subset=[COL_REVIEW_ID])

    # Reorder canonical columns for error_analysis.csv
    analysis_columns = [
        COL_REVIEW_ID,
        COL_OVERALL_RATING,
        "true_label",
        "predicted_label",
        "negative_probability",
        "positive_probability",
        COL_REVIEW_TITLE,
        COL_REVIEW_TEXT,
        COL_COMBINED_TEXT,
        "error_type",
        "text_length",
        "contains_negation",
    ]

    error_analysis_df = combined_selection[analysis_columns].copy()

    total_fps = len(fps)
    total_fns = len(fns)
    total_errors = total_fps + total_fns

    fp_negation_pct = (
        float(round((fps["contains_negation"].sum() / total_fps) * 100, 2))
        if total_fps > 0
        else 0.0
    )
    fn_negation_pct = (
        float(round((fns["contains_negation"].sum() / total_fns) * 100, 2))
        if total_fns > 0
        else 0.0
    )

    stats: dict[str, Any] = {
        "total_test_samples": len(work_df),
        "total_errors": total_errors,
        "total_false_positives": total_fps,
        "total_false_negatives": total_fns,
        "selected_analysis_samples": len(error_analysis_df),
        "false_positives_with_negation_pct": fp_negation_pct,
        "false_negatives_with_negation_pct": fn_negation_pct,
        "manual_analysis_guidelines": [
            "negação (presença de marcadores que invertem polaridade)",
            "texto muito curto (baixa contextualização)",
            "mistura entre produto e entrega (elogio ao produto mas crítica à entrega)",
            "conflito entre título e corpo (título positivo com corpo negativo ou vice-versa)",
            "possível ironia ou sarcasmo",
            "erro ortográfico severo ou abreviações não captadas",
            "texto ambíguo ou inconclusivo",
            "incongruência entre estrelas do dataset e conteúdo semântico do texto",
        ],
    }

    if output_csv_path is not None:
        out_p = Path(output_csv_path)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        error_analysis_df.to_csv(out_p, index=False, encoding="utf-8")
        logger.info(
            "Saved error analysis dataset (%d cases) to: %s",
            len(error_analysis_df),
            out_p,
        )

    return error_analysis_df, stats
